/**
 * 导出地形真相层的逐格基准，供 OceanAdventure 的 C++ 移植做 parity 比对。
 *
 * 台阶地形正在被翻译成 UE 的 C++（见 OceanAdventure 仓库
 * doc/tech/SkyLand_地形系统迁移方案.md）。翻译错一个位移、一个阈值、一个盐值，
 * 现象都是「地形看着差不多但就是对不上」——没有基准，这类错误要等到跨端不一致
 * 才暴露，那时候的症状是玩家穿模或悬空，从现象反推到某个常量打错了几乎不可能。
 *
 * 所以这里把三层各导一份：
 *
 * 1. hash32 / valueNoise 的定点探针——哈希翻错时，先在这一层就红，
 *    而不是让一整张地形图无从下手；
 * 2. terrainBiomeAt 的逐格群系；
 * 3. terrainCellCodeAt 的逐格完整 code（群系已经压在里面，第 2 项是为了定位）。
 *
 * 格 code 恒在 [0, 0xffff]（高度层占高 8 位且先 & 0xff），所以按四位十六进制写，
 * 文件既紧凑又能直接 diff。
 *
 * 用法：node scripts/export-terrain-parity.mjs [输出路径]
 */

import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { hash32, valueNoise } from '../shared/world/hash.mjs';
import { terrainBiomeAt } from '../shared/world/terrainBiome.mjs';
import { terrainCellCodeAt } from '../shared/world/terrainContent.mjs';
import { DEFAULT_WORLD_SEED } from '../shared/world/worldConfig.mjs';

/** 导出的格坐标窗口（闭区间）。129² 格覆盖出生安全区、群系边界与多种坡角。 */
const CELL_MINIMUM = -64;
const CELL_MAXIMUM = 64;

/**
 * 两颗种子：一颗是房间默认种子，一颗是 OceanCore 现有资产里的默认值。
 * 单颗种子过不了「盐值写错但恰好对上」这一关。
 */
const SEEDS = [DEFAULT_WORLD_SEED, 12345];

/** 哈希探针。坐标刻意取到负数与跨格点，定点 smoothstep 的截断在这里才会暴露。 */
const HASH_PROBES = [
  [0, 0, 0, 0],
  [1, 0, 0, 0],
  [DEFAULT_WORLD_SEED, 0, 0, 0],
  [DEFAULT_WORLD_SEED, 1, 2, 3],
  [DEFAULT_WORLD_SEED, -1, -2, -3],
  [DEFAULT_WORLD_SEED, 0x7fffffff, -0x80000000, 0x51ed270b],
  [12345, -7, 13, 0x4d2c8f13],
];

const NOISE_PROBES = [
  [0, 0, 0, 5],
  [DEFAULT_WORLD_SEED, 0, 0, 5],
  [DEFAULT_WORLD_SEED, 1, 1, 5],
  [DEFAULT_WORLD_SEED, 31, 31, 5],
  [DEFAULT_WORLD_SEED, 32, 32, 5],
  [DEFAULT_WORLD_SEED, -1, -1, 5],
  [DEFAULT_WORLD_SEED, -33, 17, 5],
  [DEFAULT_WORLD_SEED, -1000, 1000, 5],
  [12345, 5, -9, 3],
  [12345, 5, -9, 6],
];

function hex16(value) {
  return (value & 0xffff).toString(16).padStart(4, '0');
}

function formatGrid(valueAt) {
  const lines = [];
  for (let cellZ = CELL_MINIMUM; cellZ <= CELL_MAXIMUM; cellZ += 1) {
    const row = [];
    for (let cellX = CELL_MINIMUM; cellX <= CELL_MAXIMUM; cellX += 1) {
      row.push(hex16(valueAt(cellX, cellZ)));
    }
    lines.push(row.join(' '));
  }
  return lines;
}

const out = [];
out.push('# OceanTerrain parity fixture');
out.push('# generated by SkyLand scripts/export-terrain-parity.mjs — do not hand-edit');
out.push('# source of truth: shared/world/{hash,terrainBiome,terrainContent}.mjs');
out.push('#');
out.push('# 每个 grid 段是 (cellMax - cellMin + 1)² 个四位十六进制数，行主序：');
out.push('# 外层按 cellZ 从 cellMin 到 cellMax，每行内层按 cellX 从 cellMin 到 cellMax。');
out.push('# SkyLand 的 cellX 是东、cellZ 是北；UE 侧的轴映射见迁移方案第五节决策三。');
out.push(`cellMin ${CELL_MINIMUM}`);
out.push(`cellMax ${CELL_MAXIMUM}`);
out.push('');

out.push('# hash32(seed, a, b, c) -> uint32，十六进制');
for (const [seed, a, b, c] of HASH_PROBES) {
  out.push(`hash ${seed} ${a} ${b} ${c} ${hash32(seed, a, b, c).toString(16).padStart(8, '0')}`);
}
out.push('');

out.push('# valueNoise(seed, x, y, shift) -> [0, 255]，十进制');
for (const [seed, x, y, shift] of NOISE_PROBES) {
  out.push(`noise ${seed} ${x} ${y} ${shift} ${valueNoise(seed, x, y, shift)}`);
}
out.push('');

for (const seed of SEEDS) {
  out.push(`biome ${seed}`);
  out.push(...formatGrid((cellX, cellZ) => terrainBiomeAt(seed, cellX, cellZ)));
  out.push('');
  out.push(`cell ${seed}`);
  out.push(...formatGrid((cellX, cellZ) => terrainCellCodeAt(seed, cellX, cellZ)));
  out.push('');
}

const target = process.argv[2]
  ?? new URL('../../OceanAdventure/Plugins/OceanCore/Source/OceanCoreRuntime/Private/Terrain/Tests/Fixtures/terrain-parity.txt', import.meta.url).pathname;
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, `${out.join('\n')}\n`, 'utf8');
const cells = (CELL_MAXIMUM - CELL_MINIMUM + 1) ** 2;
console.log(`wrote ${target}`);
console.log(`  seeds=${SEEDS.length} cells/grid=${cells} grids=${SEEDS.length * 2}`);
